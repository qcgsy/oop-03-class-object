#include "Point.h"

#include <iostream>
#include <iomanip>
#include <cmath>

// ----------------------------------------------------------------------------
//  构造函数
// ----------------------------------------------------------------------------
Point::Point(double x, double y, double z) : x(x), y(y), z(z)
{
}

// ----------------------------------------------------------------------------
//  手工初始化
// ----------------------------------------------------------------------------
void Point::Init(double x, double y, double z)
{
    this->x = x;
    this->y = y;
    this->z = z;
}

// ----------------------------------------------------------------------------
//  读接口
// ----------------------------------------------------------------------------
double Point::getX() const { return x; }
double Point::getY() const { return y; }
double Point::getZ() const { return z; }

// ----------------------------------------------------------------------------
//  写接口
// ----------------------------------------------------------------------------
void Point::setX(double x) { this->x = x; }
void Point::setY(double y) { this->y = y; }
void Point::setZ(double z) { this->z = z; }

// ----------------------------------------------------------------------------
//  输出：(x, y, z)，各分量保留两位小数
// ----------------------------------------------------------------------------
void Point::display() const
{
    std::cout << std::fixed << std::setprecision(2)
              << '(' << x << ", " << y << ", " << z << ')';
}

// ----------------------------------------------------------------------------
//  成员函数版本：当前点到 other 的欧氏距离
//  这里 this 指向当前对象，x、y、z 相当于 this->x、this->y、this->z；
//  另一个点必须通过参数 other 传入，并通过公有接口访问其坐标。
// ----------------------------------------------------------------------------
double Point::distanceTo(const Point& other) const
{
    double dx = x - other.getX();
    double dy = y - other.getY();
    double dz = z - other.getZ();
    return std::sqrt(dx * dx + dy * dy + dz * dz);
}

// ============================================================================
//  以下为友元函数的定义：它们不是 Point 的成员函数，
//  所以函数名前不加 Point::，但可以直接访问 a.x、b.x 等私有成员。
// ============================================================================

// ----------------------------------------------------------------------------
//  欧氏距离（直线距离）：d = sqrt(dx^2 + dy^2 + dz^2)
// ----------------------------------------------------------------------------
double euclideanDistance(const Point& a, const Point& b)
{
    double dx = a.x - b.x;
    double dy = a.y - b.y;
    double dz = a.z - b.z;
    return std::sqrt(dx * dx + dy * dy + dz * dz);
}

// ----------------------------------------------------------------------------
//  曼哈顿距离（城市街区距离）：d = |dx| + |dy| + |dz|
// ----------------------------------------------------------------------------
double manhattanDistance(const Point& a, const Point& b)
{
    return std::fabs(a.x - b.x) + std::fabs(a.y - b.y) + std::fabs(a.z - b.z);
}

// ----------------------------------------------------------------------------
//  切比雪夫距离（棋盘距离）：d = max(|dx|, |dy|, |dz|)
// ----------------------------------------------------------------------------
double chebyshevDistance(const Point& a, const Point& b)
{
    double dx = std::fabs(a.x - b.x);
    double dy = std::fabs(a.y - b.y);
    double dz = std::fabs(a.z - b.z);

    double m = dx;
    if (dy > m) { m = dy; }
    if (dz > m) { m = dz; }
    return m;
}

// ----------------------------------------------------------------------------
//  中点：返回一个新的 Point 对象（按值返回，不能返回局部对象的引用或指针）
// ----------------------------------------------------------------------------
Point midpoint(const Point& a, const Point& b)
{
    return Point((a.x + b.x) / 2.0,
                 (a.y + b.y) / 2.0,
                 (a.z + b.z) / 2.0);
}

// ----------------------------------------------------------------------------
//  提高要求：重载友元函数，计算点到原点的欧氏距离
//  这是 euclideanDistance 的重载版本：参数个数不同，编译器按实参个数解析。
//     euclideanDistance(a)     -> 调用本函数（1 个参数）
//     euclideanDistance(a, b)  -> 调用上面的二参数版本
// ----------------------------------------------------------------------------
double euclideanDistance(const Point& p)
{
    return std::sqrt(p.x * p.x + p.y * p.y + p.z * p.z);
}
